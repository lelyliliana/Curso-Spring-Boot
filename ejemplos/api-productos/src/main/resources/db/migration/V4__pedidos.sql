-- V3 se reserva a los datos ficticios del perfil dev. V4 se aplica en dev y prod.
CREATE TABLE pedido (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    estado VARCHAR(16) NOT NULL,
    fecha TIMESTAMP WITH TIME ZONE NOT NULL,
    total NUMERIC(18,2) NOT NULL DEFAULT 0,
    CHECK (estado IN ('BORRADOR','CONFIRMADO','CANCELADO')),
    CHECK (total >= 0)
);
CREATE TABLE detalle_pedido (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id BIGINT NOT NULL REFERENCES pedido(id) ON DELETE CASCADE,
    producto_id BIGINT NOT NULL REFERENCES producto(id),
    cantidad INTEGER NOT NULL CHECK (cantidad BETWEEN 1 AND 10000),
    precio_unitario NUMERIC(12,2) CHECK (precio_unitario > 0),
    UNIQUE(pedido_id, producto_id)
);
CREATE INDEX detalle_pedido_producto_idx ON detalle_pedido(producto_id);
